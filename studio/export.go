// lit renders a Go string literal, preferring a raw literal for anything with
// a newline in it because a prompt is meant to be read.
func lit(s string) string {
	if strings.Contains(s, "\n") && !strings.Contains(s, "`") && !strings.Contains(s, "\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

func num(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }

func strSlice(items []string) string {
	parts := make([]string, len(items))
	for i, s := range items {
		parts[i] = lit(s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func bindingLit(tier, id string, escalate []string) string {
	b := binding(tier, id, escalate)
	var parts []string
	if b.Model != "" {
		parts = append(parts, "Model: "+lit(b.Model))
	}
	if b.Tier != "" {
		parts = append(parts, "Tier: model."+tierConst(b.Tier))
	}
	if len(b.Escalation) > 0 {
		parts = append(parts, "Escalation: "+strSlice(b.Escalation))
	}
	return "model.Binding{" + strings.Join(parts, ", ") + "}"
}

func tierConst(t model.Tier) string {
	switch t {
	case model.TierFast:
		return "TierFast"
	case model.TierBalanced:
		return "TierBalanced"
	case model.TierDeep:
		return "TierDeep"
	}
	return "Tier(" + strconv.Quote(string(t)) + ")"
}

func condLit(c Cond) string {
	return fmt.Sprintf("(studio.Cond{Field: %s, Op: %s, Value: %s})",
		lit(c.Field), lit(c.Op), lit(c.Value))
}

// marshalRecords renders inline records as the JSON blob the exported program
// decodes at startup: a document that carries its own input keeps carrying it.
func marshalRecords(recs []core.Record) (string, error) {
	b, err := json.MarshalIndent(recs, "", "  ")
	if err != nil {
		return "", err
	}
	return string(b), nil
}

// describe is the one-line comment above a generated step: what the card on
// the canvas says, so the file reads like the picture.
func describe(s *Step) string {
	title := field(s.Title, s.ID)
	switch s.Kind {
	case KindSource:
		return title + " — records in"
	case KindInfer:
		return title + " — one model call per record"
	case KindReduce:
		if s.Merging() {
			return title + " — folds " + strings.Join(s.Merge, ", ")
		}
		return title + " — folds every record into one"
	case KindLoop:
		return title + " — repeats until " + s.Loop.Until.String()
	case KindFilter:
		return title + " — keeps records where " + s.Keep.String()
	case KindDerive:
		return title + " — adds " + s.Field.Name + ", no model"
	case KindWrite:
		return title + " — writes " + s.Write.Name + " into " + s.Write.Dir
	}
	return title
}

func camel(id string) string {
	parts := strings.FieldsFunc(id, func(r rune) bool { return r == '-' || r == '_' || r == '.' })
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		if i == 0 {
			b.WriteRune(unicode.ToLower(r[0]))
		} else {
			b.WriteRune(unicode.ToUpper(r[0]))
		}
		b.WriteString(string(r[1:]))
	}
	if b.Len() == 0 {
		return "step"
	}
	return b.String()
}

